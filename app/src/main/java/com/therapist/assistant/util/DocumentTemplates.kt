package com.therapist.assistant.util

/**
 * قالب متنی اسناد — اشتراک به‌صورت متن (بدون PDF A5).
 */
object DocumentTemplates {

    data class DocDef(
        val id: String,
        val title: String,
        val description: String,
        val category: String
    )

    val catalog: List<DocDef> = listOf(
        DocDef("consent", "رضایت‌نامه آگاهانه درمان", "رضایت کتبی دریافت خدمات", "حقوقی"),
        DocDef("intake", "فرم ارزیابی اولیه", "شکایت اصلی، سابقه و اهداف", "پذیرش"),
        DocDef("session_note", "برگه ثبت جلسه (SOAP)", "ساختار S-O-A-P", "بالینی"),
        DocDef("treatment_plan", "برنامه درمان فردی", "اهداف و مداخلات", "بالینی"),
        DocDef("progress", "گزارش پیشرفت درمان", "خلاصه دوره‌ای", "گزارش"),
        DocDef("discharge", "خلاصه پایان دوره", "ترخیص و پیگیری", "گزارش"),
        DocDef("referral", "نامه ارجاع تخصصی", "ارجاع به همکار", "مکاتبه"),
        DocDef("confidentiality", "تعهدنامه محرمانگی", "حفظ اطلاعات", "حقوقی"),
        DocDef("safety_plan", "برنامه ایمنی بحران", "افکار خودآسیبی و منابع حمایتی", "بالینی"),
        DocDef("thought_record", "فرم فکر CBT", "موقعیت، فکر، شواهد، پاسخ جایگزین", "بالینی"),
        DocDef("ba_schedule", "جدول فعالیت BA", "فعال‌سازی رفتاری — لذت و تسلط", "بالینی"),
        DocDef("insurance_letter", "نامه خلاصه برای بیمه/ارگان", "سربرگ مرکز — بدون جزئیات محرمانه", "مکاتبه"),
        DocDef("homework", "برگه تکلیف خانه", "تکلیف بین جلسات", "بالینی")
    )

    fun buildText(
        id: String,
        clientName: String,
        phone: String,
        clinicName: String,
        sessionCount: Int = 0,
        nowMillis: Long = System.currentTimeMillis()
    ): String {
        val date = JalaliDate.formatDateLong(nowMillis)
        val cn = clinicName.ifBlank { "مرکز گل سرخ" }
        return when (id) {
            "consent" -> """
رضایت‌نامه آگاهانه دریافت خدمات روان‌شناختی

مرکز: $cn
مراجع: $clientName
تاریخ: $date

اینجانب $clientName با آگاهی از ماهیت خدمات روان‌شناختی، حدود محرمانگی و موارد افشای قانونی، رضایت خود را برای دریافت خدمات اعلام می‌دارم.

امضای مراجع: ........................
امضای درمانگر: ......................
""".trimIndent()
            "intake" -> """
فرم ارزیابی اولیه مراجع

مرکز: $cn
نام: $clientName
تلفن: $phone
تاریخ: $date

شکایت اصلی:
................................................

سابقه درمان قبلی:  خیر ☐   بله ☐
داروهای فعلی:
................................................

اهداف مراجع از درمان:
................................................
""".trimIndent()
            "session_note" -> """
برگه ثبت جلسه (SOAP)

مراجع: $clientName
تاریخ: $date
مرکز: $cn

S — گفته‌ها:
................................................

O — مشاهدات:
................................................

A — ارزیابی:
................................................

P — برنامه و تکلیف:
................................................

امضای درمانگر: ........................
""".trimIndent()
            "treatment_plan" -> """
برنامه درمان فردی

مراجع: $clientName
مرکز: $cn
تاریخ: $date

مسائل هدف:
................................................

اهداف کوتاه‌مدت:
................................................

اهداف بلندمدت:
................................................

مداخلات پیشنهادی:
................................................

امضای مراجع / درمانگر: ........................
""".trimIndent()
            "progress" -> """
گزارش پیشرفت درمان

مراجع: $clientName
مرکز: $cn
تاریخ: $date
تعداد جلسات: $sessionCount

تغییرات مثبت:
................................................

موانع باقی‌مانده:
................................................

برنامه ادامه:
................................................

امضای درمانگر: ........................
""".trimIndent()
            "discharge" -> """
خلاصه پایان دوره درمان

مرکز: $cn
مراجع: $clientName
تاریخ: $date
تعداد جلسات: $sessionCount

خلاصه روند:
................................................

وضعیت پایان:
................................................

پیشنهاد پیگیری:
................................................

امضای درمانگر: ........................
""".trimIndent()
            "referral" -> """
نامه ارجاع تخصصی

از: $cn
تاریخ: $date
مراجع: $clientName
تلفن: $phone

علت ارجاع:
................................................

مداخلات تاکنون:
................................................

درخواست از همکار:
................................................

با سپاس
امضا و مهر: ........................
""".trimIndent()
            "confidentiality" -> """
تعهدنامه محرمانگی اطلاعات پرونده

مرکز: $cn
مراجع: $clientName
تاریخ: $date

این مرکز متعهد است اطلاعات هویتی و بالینی مراجع را محرمانه نگه دارد و افشا را فقط در چارچوب قانون یا رضایت کتبی انجام دهد.

امضا و مهر مرکز: ........................
""".trimIndent()
            "safety_plan" -> """
برنامه ایمنی بحران

مرکز: $cn
مراجع: $clientName
تاریخ: $date

۱) نشانه‌های هشدار زودرس من:
................................................

۲) مهارت‌های آرام‌سازی که می‌توانم انجام دهم:
................................................

۳) افراد قابل تماس (نام و تلفن):
................................................

۴) متخصص / اورژانس (اورژانس اجتماعی، ۱۲۳، مرکز):
................................................

۵) محیط را ایمن‌تر می‌کنم با:
................................................

امضای مراجع: ........................
""".trimIndent()
            "thought_record" -> """
فرم ثبت فکر (CBT)

مراجع: $clientName | مرکز: $cn | تاریخ: $date

موقعیت (چه، کجا، کی):
................................................

هیجان و شدت (۰–۱۰۰):
................................................

فکر خودکار:
................................................

شواهد له:
................................................

شواهد علیه:
................................................

پاسخ جایگزین / متعادل:
................................................

شدت هیجان بعد از بازنگری (۰–۱۰۰):
................................................
""".trimIndent()
            "ba_schedule" -> """
جدول فعالیت (فعال‌سازی رفتاری)

مراجع: $clientName | مرکز: $cn | تاریخ: $date

| روز | فعالیت | ساعت | لذت (۰–۱۰) | تسلط (۰–۱۰) | انجام شد |
|-----|---------|------|------------|-------------|---------|
| شنب |         |      |            |             |         |
| یکش |         |      |            |             |         |
| دوش |         |      |            |             |         |
| سه‌ش |        |      |            |             |         |
| چهار |        |      |            |             |         |
| پنج |         |      |            |             |         |
| جمعه|         |      |            |             |         |

دو فعالیت اولویت این هفته:
۱) ................................................
۲) ................................................
""".trimIndent()
            "insurance_letter" -> """
$cn
$date

موضوع: تأیید دریافت خدمات روان‌شناختی

بدین‌وسیله تأیید می‌شود که خانم/آقای $clientName در این مرکز تحت خدمات مشاوره/روان‌درمانی قرار گرفته‌اند.
تعداد جلسات ثبت‌شده تا این تاریخ: $sessionCount

این نامه فاقد جزئیات بالینی محرمانه است و صرفاً جهت ارائه به ارگان درخواست‌کننده صادر شده است.

مهر و امضای مرکز: ........................
""".trimIndent()
            "homework" -> """
برگه تکلیف بین جلسات

مراجع: $clientName | مرکز: $cn | تاریخ: $date

تکلیف توافق‌شده:
................................................

زمان انجام:
................................................

موانع احتمالی و راه‌حل:
................................................

نتیجه (برای جلسه بعد):
................................................
""".trimIndent()
            else -> buildText("intake", clientName, phone, clinicName, sessionCount, nowMillis)
        }
    }
}
