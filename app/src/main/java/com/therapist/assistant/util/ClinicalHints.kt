package com.therapist.assistant.util

/**
 * پیشنهاد نرم‌افزاری پس از نمره آزمون — جایگزین قضاوت بالینی نیست.
 */
object ClinicalHints {
    fun forScore(type: String, score: Int): String {
        val base = when (type.uppercase()) {
            "PHQ9" -> when {
                score >= 20 -> "نمره در محدوده شدید است. بررسی ایمنی، افکار آسیب به خود و ارجاع فوری در صورت نیاز پیشنهاد می‌شود."
                score >= 15 -> "نمره متوسط تا شدید. پیگیری منظم، ارزیابی عملکرد روزانه و در صورت صلاحدید مداخله ساختاریافته."
                score >= 10 -> "نمره خفیف تا متوسط. پایش هفتگی و فعال‌سازی رفتاری می‌تواند مفید باشد."
                score >= 5 -> "علائم خفیف. آموزش روانی و پیگیری در جلسه بعد."
                else -> "زیر آستانه غربالگری رایج. در صورت شکایت بالینی، ارزیابی کیفی ادامه یابد."
            }
            "GAD7" -> when {
                score >= 15 -> "اضطراب شدید احتمالی. تکنیک‌های تنظیم هیجان و بررسی اجتناب موقعیتی پیشنهاد می‌شود."
                score >= 10 -> "اضطراب متوسط. تمرین تنفس/آرام‌سازی و بازسازی شناختی می‌تواند کمک‌کننده باشد."
                score >= 5 -> "اضطراب خفیف. پایش و آموزش مدیریت استرس."
                else -> "زیر آستانه غربالگری اضطراب رایج."
            }
            "DASS21" -> "نمرات DASS را در سه زیرمقیاس افسردگی/اضطراب/استرس جدا تفسیر کنید؛ پیشنهاد مداخله متناسب با بالاترین زیرمقیاس."
            "ISI" -> when {
                score >= 15 -> "اختلال خواب بالینی محتمل. بهداشت خواب و در صورت تداوم ارجاع تخصصی خواب."
                score >= 8 -> "بی‌خوابی خفیف تا متوسط. برنامه منظم خواب و محدود کردن صفحه نمایش شبانه."
                else -> "وضعیت خواب در محدوده قابل قبول غربالگری."
            }
            "AUDIT10", "AUDIT_C", "CAGE" -> "در صورت نمره بالا، مصاحبه انگیزشی و بررسی نیاز به ارجاع اعتیاد پیشنهاد می‌شود."
            else -> "نتیجه را در بافت بالینی مراجع تفسیر کنید و در صورت لزوم آزمون مکمل اجرا کنید."
        }
        return "⚠️ پیشنهاد نرم‌افزاری (جایگزین تشخیص بالینی نیست):\n$base"
    }
}
